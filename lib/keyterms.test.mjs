// node --experimental-strip-types lib/keyterms.test.mjs
import { sanitizeGlossary, sanitizeNames, keytermParams, cleanTerm, glossaryPath, MAX_GLOSSARY_TERMS } from "./keyterms.ts";
let pass = 0, fail = 0;
const ok = (c, m) => { c ? pass++ : fail++; console.log(`  ${c ? "ok  " : "FAIL"} - ${m}`); };
ok(JSON.stringify(sanitizeGlossary("LiveKit, Deepgram\nQuantlys; livekit")) === '["LiveKit","Deepgram","Quantlys"]', "splits on , ; newline and dedupes case-insensitively");
ok(cleanTerm("<script>alert(1)</script>") === "script alert 1 script", "strips markup characters");
ok(cleanTerm("x".repeat(100)).length === 40, "caps term length");
ok(sanitizeGlossary(Array.from({ length: 80 }, (_, i) => `term${i}`)).length === MAX_GLOSSARY_TERMS, "caps at 50 terms");
ok(sanitizeGlossary("a, , ,b").length === 0, "drops 1-char and empty terms");
ok(JSON.stringify(sanitizeGlossary("José Núñez, 東京")) === '["José Núñez","東京"]', "keeps non-latin letters");
ok(JSON.stringify(sanitizeNames(["Santosh Adari", "Guest 3", "guest", "Maya"])) === '["Santosh Adari","Maya"]', "drops generic guest names");
const n3 = keytermParams("nova-3", ["Santosh Adari"], ["PRD", "LiveKit"]);
ok(n3.every(([k]) => k === "keyterm") && n3[0][1] === "Santosh Adari", "nova-3 uses keyterm with phrases");
const n2 = keytermParams("nova-2", ["Santosh Adari"], ["PRD", "prd"]);
ok(JSON.stringify(n2) === '[["keywords","Santosh:2"],["keywords","Adari:2"],["keywords","PRD:2"]]', "nova-2 uses single-word keywords with boost, deduped");
const qs = new URLSearchParams([["model", "nova-2"], ...n2]).toString();
ok(qs.includes("keywords=Santosh%3A2&keywords=Adari%3A2"), "serialises as repeated params");
ok(keytermParams("nova-2", [], []).length === 0, "nothing to boost → no params");
ok(glossaryPath("u1", "Abc-123 X") === "u1/prd/abc-123-x.glossary.json", "glossary lives in host prd/ folder");
console.log(`\n${pass} passed, ${fail} failed`); if (fail) process.exit(1);
