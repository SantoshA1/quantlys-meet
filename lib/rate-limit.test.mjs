// node --experimental-strip-types lib/rate-limit.test.mjs
import { hit, rateLimit, clientIp } from "./rate-limit.ts";
let pass = 0, fail = 0;
const ok = (c, m) => { c ? pass++ : fail++; console.log(`  ${c ? "ok  " : "FAIL"} - ${m}`); };
const lim = { limit: 3, windowMs: 1000 };
const t0 = 1_000_000;
ok(hit("a", lim, t0).ok && hit("a", lim, t0).ok && hit("a", lim, t0).ok, "first N requests pass");
ok(!hit("a", lim, t0).ok, "N+1th request in the window is refused");
ok(hit("a", lim, t0 + 1001).ok, "a new window resets the budget");
ok(hit("b", lim, t0).ok, "buckets are per key");
const req = (ip) => new Request("https://x/api", { headers: { "x-forwarded-for": `${ip}, 10.0.0.1` } });
ok(clientIp(req("1.2.3.4")) === "1.2.3.4", "client IP is the first x-forwarded-for hop");
let last = null;
for (let i = 0; i < 4; i++) last = await rateLimit(req("9.9.9.9"), "t", lim);
ok(last && last.status === 429 && last.headers.get("Retry-After"), "over budget returns 429 with Retry-After");
ok((await rateLimit(req("8.8.8.8"), "t", lim)) === null, "another IP is unaffected");
// DB path: a missing table / failing RPC must degrade to memory, then back off.
process.env.NEXT_PUBLIC_SUPABASE_URL = "https://fake.supabase.co";
process.env.SUPABASE_SERVICE_ROLE_KEY = "svc";
let calls = 0;
globalThis.fetch = async () => { calls++; return new Response('{"code":"PGRST202"}', { status: 404 }); };
ok((await rateLimit(req("7.7.7.7"), "db", lim)) === null && calls === 1, "missing RPC falls back to memory without failing the request");
await rateLimit(req("7.7.7.7"), "db", lim);
ok(calls === 1, "after a DB failure the RPC is not retried for a minute");
const { hitDb } = await import("./rate-limit.ts");
globalThis.__qmRateState.dbOffUntil = 0;
globalThis.fetch = async () => new Response(JSON.stringify([{ hits: 4, reset_at: new Date(Date.now() + 30000).toISOString() }]), { status: 200 });
const r = await hitDb("x", lim);
ok(r && r.ok === false && r.remaining === 0, "DB result over the limit is refused (shared window)");
process.env.RATE_LIMIT_DISABLED = "1";
ok((await rateLimit(req("9.9.9.9"), "t", lim)) === null, "RATE_LIMIT_DISABLED=1 turns it off");
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
